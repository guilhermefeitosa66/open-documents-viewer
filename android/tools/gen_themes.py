#!/usr/bin/env python3
"""Generates ThemeCatalog.kt from docs/themes/themes.json (a copy of libre-apps-themes).

The colors live in code instead of being parsed at startup: no JSON work on the launch path.
Run from the repository root after updating docs/themes/themes.json:

    python3 tools/gen_themes.py

Roles the shared palette does not name are mapped to existing keys, never to new colors:
annotation and keys -> syntax.attribute, sections -> syntax.type, markdown markers ->
syntax.operator, links -> ui.link, code in markdown source -> syntax.string, current search
match -> ui.accent on ui.onAccent, line numbers -> ui.textMuted.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/themes/themes.json"
OUT = ROOT / "app/src/main/kotlin/io/github/guilhermefeitosa66/opendocumentsviewer/ui/theme/ThemeCatalog.kt"


def c(hex_):
    return f"Color(0xFF{hex_.lstrip('#').upper()})"


def theme(t):
    ui, sx, md = t["ui"], t["syntax"], t["markdown"]
    dark = "true" if t["scheme"] == "dark" else "false"
    syntax = f"""SyntaxColors(
            keyword = {c(sx['keyword'])},
            literal = {c(sx['constant'])},
            type = {c(sx['type'])},
            string = {c(sx['string'])},
            number = {c(sx['number'])},
            comment = {c(sx['comment'])},
            function = {c(sx['function'])},
            annotation = {c(sx['attribute'])},
            variable = {c(sx['variable'])},
            key = {c(sx['attribute'])},
            section = {c(sx['type'])},
            tag = {c(sx['tag'])},
            attribute = {c(sx['attribute'])},
            punctuation = {c(sx['punctuation'])},
            heading = {c(md['heading'])},
            markup = {c(sx['operator'])},
            link = {c(ui['link'])},
            code = {c(sx['string'])},
        )"""
    colors = f"""OdvColors(
        paper = {c(ui['bg'])},
        paper2 = {c(ui['surfaceAlt'])},
        card = {c(ui['surface'])},
        ink = {c(ui['text'])},
        ink2 = {c(ui['textMuted'])},
        line = {c(ui['border'])},
        accent = {c(ui['accent'])},
        accentInk = {c(ui['link'])},
        onAccent = {c(ui['onAccent'])},
        gutter = {c(ui['textMuted'])},
        codeBackground = {c(md['codeBg'])},
        inlineCode = {c(md['codeBg'])},
        quoteBackground = {c(ui['surfaceAlt'])},
        match = {c(ui['searchHit'])},
        currentMatch = {c(ui['accent'])},
        onCurrentMatch = {c(ui['onAccent'])},
        pill = {c(ui['text'])},
        onPill = {c(ui['bg'])},
        pillSelected = {c(ui['bg'])},
        dark = {dark},
        syntax = {syntax},
        headingColor = {c(md['heading'])},
        quoteBar = {c(md['quoteBar'])},
        rule = {c(md['hr'])},
        selection = {c(ui['selection'])},
    )"""
    return f"""    val {t["id"].upper()} = AppTheme(
        id = "{t['id']}",
        name = "{t['name']}",
        background = "backgrounds/{t['id']}.webp",
        light = {colors},
    )"""


def main():
    data = json.loads(SRC.read_text())
    themes = data["themes"]
    body = "\n\n".join(theme(t) for t in themes)
    ids = ", ".join(t["id"].upper() for t in themes)
    OUT.write_text(f"""// Generated by tools/gen_themes.py from docs/themes/themes.json. Do not edit by hand.
package io.github.guilhermefeitosa66.opendocumentsviewer.ui.theme

import androidx.compose.ui.graphics.Color

object ThemeCatalog {{
{body}

    /** The shared libre-apps themes, after the default (libre-apps following the system). */
    val extras: List<AppTheme> = listOf({ids})
}}
""")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(themes)} themes)")


if __name__ == "__main__":
    main()
