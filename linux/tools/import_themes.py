"""Import the shared libre-apps themes into this repository.

    python3 tools/import_themes.py ~/projetos/pessoal/libre-apps-themes

Copies themes.json and the landscape backgrounds, makes small thumbnails for
the theme picker, generates a GtkSourceView style scheme per theme from its
``syntax`` colours and prints a contrast report. The app never reads the
themes folder itself: what it uses is committed under src/odv/data/themes.
"""

import json
import os
import shutil
import sys

import gi

gi.require_version("GdkPixbuf", "2.0")
from gi.repository import GdkPixbuf  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DATA = os.path.join(ROOT, "src", "odv", "data")
THUMB = (320, 180)

# GtkSourceView style ids -> the theme's syntax role.
SYNTAX_MAP = {
    "def:keyword": "keyword", "def:statement": "keyword", "def:preprocessor": "keyword",
    "def:string": "string", "def:character": "string", "def:special-char": "constant",
    "def:number": "number", "def:floating-point": "number", "def:decimal": "number",
    "def:base-n-integer": "number", "def:comment": "comment", "def:doc-comment": "comment",
    "def:shebang": "comment", "def:function": "function", "def:type": "type", "def:builtin": "type",
    "def:identifier": "variable", "def:constant": "constant", "def:special-constant": "constant",
    "def:boolean": "constant", "def:operator": "operator", "def:net-address": "string",
    "xml:element-name": "tag", "xml:attribute-name": "attribute", "html:tag": "tag",
    "def:heading": "keyword",
}


def luminance(hex_color):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def scheme_xml(theme):
    ui, syn, md = theme["ui"], theme["syntax"], theme["markdown"]
    parent = "Adwaita-dark" if theme["scheme"] == "dark" else "Adwaita"
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<!-- Generated by tools/import_themes.py from the libre-apps theme "{theme["id"]}". -->',
        f'<style-scheme id="odv-{theme["id"]}" name="{theme["name"]}" version="1.0" '
        f'parent-scheme="{parent}" kind="{theme["scheme"]}">',
        f'  <style name="text" foreground="{ui["text"]}" background="{ui["bg"]}"/>',
        f'  <style name="line-numbers" foreground="{ui["textMuted"]}" background="{ui["bg"]}"/>',
        f'  <style name="current-line-number" foreground="{ui["text"]}" background="{ui["bg"]}" bold="true"/>',
        f'  <style name="selection" foreground="{ui["text"]}" background="{ui["selection"]}"/>',
        f'  <style name="selection-unfocused" foreground="{ui["text"]}" background="{ui["selection"]}"/>',
        f'  <style name="search-match" background="{ui["searchHit"]}"/>',
        f'  <style name="bracket-match" background="{ui["selection"]}" bold="true"/>',
        f'  <style name="markdown:header" foreground="{md["heading"]}" bold="true"/>',
    ]
    for style, key in (("def:link-text", "link"), ("def:link-destination", "link")):
        lines.append(f'  <style name="{style}" foreground="{ui[key]}" underline="single"/>')
    lines.append(f'  <style name="def:link-symbol" foreground="{syn["punctuation"]}"/>')
    # Log levels and diagnostics (odv-log and others) use the theme's status colours.
    lines.append(f'  <style name="def:error" foreground="{ui["error"]}" bold="true"/>')
    lines.append(f'  <style name="def:warning" foreground="{ui["warning"]}" bold="true"/>')
    lines.append(f'  <style name="def:note" foreground="{ui["success"]}"/>')
    for style, role in SYNTAX_MAP.items():
        extra = ' italic="true"' if role == "comment" else (' bold="true"' if role == "keyword" else "")
        lines.append(f'  <style name="{style}" foreground="{syn[role]}"{extra}/>')
    lines.append("</style-scheme>")
    return "\n".join(lines) + "\n"


def main():
    src = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/projetos/pessoal/libre-apps-themes")
    with open(os.path.join(src, "themes.json")) as f:
        data = json.load(f)
    out = os.path.join(DATA, "themes")
    for sub in ("backgrounds", "thumbs"):
        os.makedirs(os.path.join(out, sub), exist_ok=True)
    os.makedirs(os.path.join(DATA, "styles"), exist_ok=True)

    for theme in data["themes"]:
        tid = theme["id"]
        # themes.json's "background" names backgrounds/svg/<id>.svg, which the
        # pack does not have; its files follow <id>-landscape / <id>-portrait.
        png = os.path.join(src, "backgrounds", "png", f"{tid}-landscape.png")
        shutil.copyfile(png, os.path.join(out, "backgrounds", f"{tid}.png"))
        thumb = GdkPixbuf.Pixbuf.new_from_file_at_scale(png, THUMB[0], THUMB[1], False)
        thumb.savev(os.path.join(out, "thumbs", f"{tid}.png"), "png", [], [])
        theme["background"] = f"backgrounds/{tid}.png"
        theme["thumbnail"] = f"thumbs/{tid}.png"
        with open(os.path.join(DATA, "styles", f"odv-{tid}.xml"), "w") as f:
            f.write(scheme_xml(theme))
        ui = theme["ui"]
        print(f"{tid:8} text/bg {contrast(ui['text'], ui['bg']):5.2f}  text/surface "
              f"{contrast(ui['text'], ui['surface']):5.2f}  muted/bg {contrast(ui['textMuted'], ui['bg']):5.2f}  "
              f"muted/surface {contrast(ui['textMuted'], ui['surface']):5.2f}  "
              f"link/bg {contrast(ui['link'], ui['bg']):5.2f}  onAccent/accent "
              f"{contrast(ui['onAccent'], ui['accent']):5.2f}")
    data["$source"] = "Imported from libre-apps-themes by tools/import_themes.py; do not edit by hand."
    with open(os.path.join(out, "themes.json"), "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


if __name__ == "__main__":
    main()
